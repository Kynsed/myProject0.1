        public static bool Ready => texture != null;

        public static void Load(GraphicsDevice device)
        {
            if (texture != null)
                return;
            int count = Last - First + 1;
            int w = count * Advance;
            var pixels = new Color[w * GlyphHeight];
            glyphs = new Rectangle[count];

            for (int i = 0; i < count; i++)
            {
                int ox = i * Advance;
                glyphs[i] = new Rectangle(ox, 0, GlyphWidth, GlyphHeight);
                for (int col = 0; col < GlyphWidth; col++)
                {
                    int idx = i * GlyphWidth + col;
                    byte bits = idx < Data.Length ? Data[idx] : (byte)0;
                    for (int row = 0; row < GlyphHeight; row++)
                        if ((bits & (1 << row)) != 0)
                            pixels[row * w + ox + col] = Color.White;
                }
            }

            texture = new Texture2D(device, w, GlyphHeight);
            texture.SetData(pixels);
        }

        public static void Unload()
        {
            texture?.Dispose();
            texture = null;
        }

        public static int Measure(string text, int scale = 1)
            => string.IsNullOrEmpty(text) ? 0 : text.Length * Advance * scale;

        public static void Draw(SpriteBatch batch, string text, Vector2 at, Color color, int scale = 1)
        {
            if (texture == null || string.IsNullOrEmpty(text))
                return;
            float x = at.X;
            for (int i = 0; i < text.Length; i++)
            {
                char c = text[i];
                if (c >= First && c <= Last)
                {
                    var src = glyphs[c - First];
                    batch.Draw(texture, new Vector2(x, at.Y), src, color, 0f, Vector2.Zero,
                        scale, SpriteEffects.None, 0f);
                }
                x += Advance * scale;
            }
        }

        /// Corta o texto com reticencias para caber em maxWidth pixels.
        public static string Fit(string text, int maxWidth, int scale = 1)
        {
            if (string.IsNullOrEmpty(text))
                return string.Empty;
            int adv = Advance * scale;
            int max = maxWidth / adv;
            if (text.Length <= max)
                return text;
            if (max <= 1)
                return max == 1 ? "." : string.Empty;
            return text.Substring(0, max - 1) + ".";
        }
